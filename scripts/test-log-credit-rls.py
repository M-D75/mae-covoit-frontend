#!/usr/bin/env python3
"""Test migration 030 twice on a disposable local PostgreSQL cluster, no network."""
from pathlib import Path
import os
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
bin_dir = Path(os.environ.get('POSTGRES_BIN', '/opt/homebrew/bin'))
for command in ('initdb', 'pg_ctl', 'psql'):
    if not (bin_dir / command).exists():
        raise SystemExit('Set POSTGRES_BIN to the directory containing initdb, pg_ctl and psql.')
with tempfile.TemporaryDirectory(prefix='covia-log-credit-') as directory:
    tmp = Path(directory)
    cluster = tmp / 'data'
    subprocess.run([str(bin_dir / 'initdb'), '-D', str(cluster), '-A', 'trust', '--no-locale', '-E', 'UTF8'], check=True, capture_output=True)
    subprocess.run([str(bin_dir / 'pg_ctl'), '-D', str(cluster), '-l', str(tmp / 'postgres.log'), '-o', f"-k {tmp} -p 55441 -c listen_addresses=''", 'start'], check=True, capture_output=True)
    base = [str(bin_dir / 'psql'), '-X', '-h', str(tmp), '-p', '55441', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-At']
    def sql(statement, success=True):
        result = subprocess.run(base + ['-c', statement], capture_output=True, text=True)
        if success and result.returncode:
            raise AssertionError(result.stderr)
        if not success:
            assert result.returncode and 'permission denied' in result.stderr, result.stderr
        return result.stdout.strip()
    try:
        sql('''create role anon; create role authenticated; create role service_role;
            create table public.log_credit(id bigint generated by default as identity primary key,
                created_at timestamptz default now(), amount double precision not null default 0, account_id bigint);
            grant all on public.log_credit to anon, authenticated, service_role;
            grant all on sequence public.log_credit_id_seq to anon, authenticated, service_role;
            grant select(amount) on public.log_credit to public, authenticated;
            create policy legacy_public on public.log_credit for all to public using(true) with check(true);
            insert into public.log_credit(amount,account_id) values(7.5,42);''')
        migration = root / 'supabase/migrations/030_secure_log_credit.sql'
        snapshots = []
        for run in range(2):
            subprocess.run(base + ['-f', str(migration)], check=True, capture_output=True, text=True)
            assert sql("select relrowsecurity from pg_class where oid='public.log_credit'::regclass") == 't'
            assert sql("select count(*) from public.log_credit where amount=7.5 and account_id=42") == '1'
            for role in ('anon', 'authenticated'):
                for privilege in ('SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER'):
                    assert sql(f"select has_table_privilege('{role}', 'public.log_credit', '{privilege}')") == 'f'
                for privilege in ('SELECT', 'INSERT', 'UPDATE', 'REFERENCES'):
                    assert sql(f"select has_any_column_privilege('{role}', 'public.log_credit', '{privilege}')") == 'f'
                for privilege in ('USAGE', 'SELECT', 'UPDATE'):
                    assert sql(f"select has_sequence_privilege('{role}', 'public.log_credit_id_seq', '{privilege}')") == 'f'
                for operation in ('select * from public.log_credit', 'select amount from public.log_credit',
                    'insert into public.log_credit(amount) values(1)', 'update public.log_credit set amount=999',
                    'delete from public.log_credit', 'truncate public.log_credit',
                    "select nextval('public.log_credit_id_seq')"):
                    sql(f'set role {role}; {operation}', success=False)
            assert sql("set role service_role; select amount from public.log_credit where account_id=42").endswith('7.5')
            sql("set role service_role; insert into public.log_credit(amount,account_id) values(1,99); update public.log_credit set amount=2 where account_id=99; delete from public.log_credit where account_id=99")
            snapshots.append(sql("select policyname,roles,cmd from pg_policies where schemaname='public' and tablename='log_credit'"))
        assert snapshots[0] == snapshots[1]
        assert 'service_role' in snapshots[0] and 'ALL' in snapshots[0]
        print('PASS: RLS, table/column/sequence grants, actual anonymous/authenticated denial, service-only CRUD without BYPASSRLS, existing data preserved, migration rerun.')
    finally:
        subprocess.run([str(bin_dir / 'pg_ctl'), '-D', str(cluster), 'stop', '-m', 'fast'], check=True, capture_output=True)

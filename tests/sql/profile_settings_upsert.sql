-- Reproduce the production failure when imported rows outpace the sequence.
select setval(pg_get_serial_sequence('public.settings', 'id'), 3, false);
do $$
begin
    begin
        insert into public.settings (account_id) values (2)
            on conflict (account_id) do nothing;
        raise exception 'Expected settings_pkey collision';
    exception when unique_violation then
        raise notice 'Reproduced settings primary-key collision (23505)';
    end;
end;
$$;

\ir ../../supabase/migrations/024_repair_settings_id_sequence.sql
\ir ../../supabase/migrations/024_repair_settings_id_sequence.sql

insert into public.settings (account_id) values (2)
    on conflict (account_id) do nothing;
insert into public.settings (account_id) values (1), (2)
    on conflict (account_id) do nothing;

do $$
begin
    if (select count(*) from public.settings where account_id = 2) <> 1 then
        raise exception 'Retries must create exactly one preferences row';
    end if;
    if (select auto_accept_trip from public.settings where account_id = 1) then
        raise exception 'Existing preferences must remain unchanged';
    end if;
    if (select count(*) from public.settings where account_id is null) <> 2 then
        raise exception 'Existing NULL rows must remain unchanged';
    end if;
end;
$$;

-- A healthy sequence must never be reset backwards.
select setval(pg_get_serial_sequence('public.settings', 'id'), 100, true);
\ir ../../supabase/migrations/024_repair_settings_id_sequence.sql
do $$
begin
    if nextval(pg_get_serial_sequence('public.settings', 'id')) <> 101 then
        raise exception 'Repair must not rewind an advanced sequence';
    end if;
end;
$$;
